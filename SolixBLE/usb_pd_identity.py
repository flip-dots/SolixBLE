def vendor_name(device_class: int) -> str | None:
    """Return the vendor of a vendor class.

    :param device_class: The class from :data:`~SolixBLE.constructs.DEVICE_IDENTITY`.
    :returns: The vendor's name, or None if the class is unnamed or unknown.
    """
    return VENDOR_NAMES.get(device_class)


def device_name(device_class: int, code: int) -> str | None:
    """Return the firmware's name for an identified device.

    :param device_class: The class from :data:`~SolixBLE.constructs.DEVICE_IDENTITY`.
    :param code: The model code from the same identity.
    :returns: The name without trailing spaces, or None if the firmware has no
        record for the pair.
    """
    name = DEVICE_NAMES.get((device_class, code))
    return None if name is None else name.rstrip()
